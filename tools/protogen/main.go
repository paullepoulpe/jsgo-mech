// protogen writes go/closure/rt_proto_gen.go: the protobuf-java generated-code
// API (messages, builders, enums) of the Closure Compiler .proto files, in the
// naming scheme of the j2go translator. The generic runtime it sits on is
// go/closure/rt_proto.go.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	messages = map[string]*Message{} // by proto full name
	enums    = map[string]*Enum{}
	allMsgs  []*Message
	allEnums []*Enum

	goNames   = map[string]string{} // Java binary name -> Go name (g_0names.go)
	usedGo    = map[string]string{} // Go name -> Java binary name
	stubIface = map[string]bool{}   // interfaces declared by g_zstubs.go
	newNames  [][2]string           // Go name, Java name: classes g_0names.go lacks

	extMethods []extEntry
	extFuncs   []extEntry
	problems   []string
)

// extEntry is one line of externals.tsv.
type extEntry struct {
	owner  string // Go type (methods)
	goName string
	java   string // Java method name
	params string // Go parameter types, ", "-separated
	ret    string
	seen   bool
	rel    string // goName without the class prefix (functions)
}

func die(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "protogen: "+format+"\n", args...)
	os.Exit(1)
}

func main() {
	root := flag.String("root", ".", "project root")
	out := flag.String("out", "", "output file")
	flag.Parse()
	closure := filepath.Join(*root, "go", "closure")
	if *out == "" {
		*out = filepath.Join(closure, "rt_proto_gen.go")
	}
	readNames(filepath.Join(closure, "g_0names.go"))
	readStubs(filepath.Join(closure, "g_zstubs.go"))
	readExternals(filepath.Join(closure, "externals.tsv"))

	var paths []string
	filepath.Walk(filepath.Join(*root, "java", "src"), func(p string, info os.FileInfo, err error) error {
		if err == nil && !info.IsDir() && strings.HasSuffix(p, ".proto") {
			paths = append(paths, p)
		}
		return nil
	})
	sort.Strings(paths)
	if len(paths) == 0 {
		die("no .proto files under %s/java/src", *root)
	}
	var files []*File
	for _, p := range paths {
		f := parseFile(p)
		rel, _ := filepath.Rel(*root, p)
		f.Path = filepath.ToSlash(rel)
		files = append(files, f)
		declare(f)
	}
	for _, m := range allMsgs {
		resolve(m)
	}

	g := &gen{}
	g.p("// Code generated by tools/protogen from the .proto files under java/src. DO NOT EDIT.")
	g.p("// Regenerate with tools/protogen/run.sh.")
	g.p("")
	g.p("package closure")
	for _, f := range files {
		g.p("")
		g.p("// ================================================================ %s", f.Path)
		for _, e := range allEnums {
			if e.File == f {
				g.enum(e)
			}
		}
		for _, m := range allMsgs {
			if m.File == f {
				g.message(m)
			}
		}
	}
	if len(newNames) > 0 {
		g.p("")
		g.p("func init() {")
		for _, n := range newNames {
			g.p("\tjavaNames_[%q] = %q", n[0], n[1])
		}
		g.p("}")
	}
	if err := os.WriteFile(*out, []byte(g.sb.String()), 0o644); err != nil {
		die("%v", err)
	}

	for _, e := range append(extMethods, extFuncs...) {
		if !e.seen && e.owner != "" && ownedTypes[e.owner] {
			problems = append(problems, fmt.Sprintf("externals.tsv member not generated: %s.%s(%s) %s", e.owner, e.goName, e.params, e.ret))
		}
	}
	for _, e := range extFuncs {
		if !e.seen && ownedFunc(e.goName) {
			problems = append(problems, fmt.Sprintf("externals.tsv function not generated: %s(%s) %s", e.goName, e.params, e.ret))
		}
	}
	for _, p := range problems {
		fmt.Fprintln(os.Stderr, "protogen: warning:", p)
	}
	fmt.Fprintf(os.Stderr, "protogen: %d files, %d messages, %d enums -> %s\n", len(files), len(allMsgs), len(allEnums), *out)
}

// ---------------------------------------------------------------- inputs from the translator

func readLines(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		die("%v", err)
	}
	defer f.Close()
	var lines []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<26)
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	return lines
}

func readNames(path string) {
	re := regexp.MustCompile(`^\s*"([^"]+)":\s*"([^"]+)",`)
	for _, line := range readLines(path) {
		if m := re.FindStringSubmatch(line); m != nil {
			goNames[m[2]] = m[1]
			usedGo[m[1]] = m[2]
		}
	}
}

func readStubs(path string) {
	re := regexp.MustCompile(`^type (\w+) interface`)
	for _, line := range readLines(path) {
		if m := re.FindStringSubmatch(line); m != nil {
			stubIface[m[1]] = true
		}
	}
}

func readExternals(path string) {
	// func GoName<TAB>static a.b.C.name(P, Q) R
	// method Owner.goName<TAB>method a.b.C.name(P, Q) R
	re := regexp.MustCompile(`^(func|method) (\S+)\t(\w+) ([^(]*)\((.*?)\)(?: (.*))?$`)
	for _, line := range readLines(path) {
		m := re.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		fq := m[4]
		e := extEntry{goName: m[2], java: fq[strings.LastIndex(fq, ".")+1:], params: m[5], ret: m[6]}
		if m[1] == "method" {
			dot := strings.Index(m[2], ".")
			e.owner, e.goName = m[2][:dot], m[2][dot+1:]
			extMethods = append(extMethods, e)
		} else if m[3] == "static" {
			extFuncs = append(extFuncs, e)
		}
	}
}

// ---------------------------------------------------------------- naming

func camel(s string, capFirst bool) string {
	var sb strings.Builder
	up := capFirst
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z':
			if up {
				c -= 'a' - 'A'
			}
			sb.WriteByte(c)
			up = false
		case c >= 'A' && c <= 'Z':
			sb.WriteByte(c)
			up = false
		case c >= '0' && c <= '9':
			sb.WriteByte(c)
			up = true
		default:
			up = true
		}
	}
	return sb.String()
}

func outerClass(f *File) string {
	if n, ok := f.Options["java_outer_classname"]; ok {
		return n[1:]
	}
	base := filepath.Base(f.Path)
	base = strings.TrimSuffix(base, ".proto")
	name := camel(base, true)
	for _, m := range f.Messages {
		if m.Name == name {
			return name + "OuterClass"
		}
	}
	for _, e := range f.Enums {
		if e.Name == name {
			return name + "OuterClass"
		}
	}
	return name
}

func javaPackage(f *File) string {
	if n, ok := f.Options["java_package"]; ok {
		return n[1:]
	}
	return f.Package
}

// goName is the translator's name for a Java class (by binary name).
func goName(java string, pkg string) string {
	if n, ok := goNames[java]; ok {
		return n
	}
	raw := strings.NewReplacer("$", "_", ".", "_").Replace(strings.TrimPrefix(java, pkg+"."))
	n := raw
	if _, clash := usedGo[n]; clash {
		n = raw + "_" + pkg[strings.LastIndex(pkg, ".")+1:]
		for {
			if _, clash := usedGo[n]; !clash {
				break
			}
			n += "_"
		}
	}
	usedGo[n] = java
	goNames[java] = n
	newNames = append(newNames, [2]string{n, java})
	return n
}

var ownedTypes = map[string]bool{}

func ownedFunc(name string) bool {
	for t := range ownedTypes {
		if strings.HasPrefix(name, t+"_") {
			rest := name[len(t)+1:]
			// A longer owned type name wins (TypedAst_List_newBuilder).
			longer := false
			for u := range ownedTypes {
				if len(u) > len(t) && strings.HasPrefix(name, u+"_") {
					longer = true
				}
			}
			if !longer && rest != "" {
				return true
			}
		}
	}
	return false
}

func declare(f *File) {
	pkg := javaPackage(f)
	prefix := pkg + "."
	if f.Options["java_multiple_files"] != "true" {
		prefix += outerClass(f) + "$"
	}
	scope := ""
	if f.Package != "" {
		scope = f.Package + "."
	}
	var declMsg func(m *Message, scope, java string)
	declEnum := func(e *Enum, scope, java string) {
		e.FullName = scope + e.Name
		e.Java = java + e.Name
		e.Go = goName(e.Java, pkg)
		e.Closed = f.Syntax == "proto2" || f.Syntax == "editions" && f.Options["features.enum_type"] == "CLOSED"
		enums[e.FullName] = e
		allEnums = append(allEnums, e)
		ownedTypes[e.Go] = true
	}
	declMsg = func(m *Message, scope, java string) {
		m.FullName = scope + m.Name
		m.Java = java + m.Name
		m.Go = goName(m.Java, pkg)
		m.GoB = goName(m.Java+"$Builder", pkg)
		m.GoOB = goName(m.Java+"OrBuilder", pkg)
		messages[m.FullName] = m
		allMsgs = append(allMsgs, m)
		ownedTypes[m.Go] = true
		ownedTypes[m.GoB] = true
		ownedTypes[m.GoOB] = true
		for _, e := range m.Enums {
			declEnum(e, m.FullName+".", m.Java+"$")
		}
		for _, n := range m.Messages {
			declMsg(n, m.FullName+".", m.Java+"$")
		}
		for _, o := range m.Oneofs {
			ownedTypes[goName(m.Java+"$"+camel(o, true)+"Case", pkg)] = true
		}
	}
	for _, e := range f.Enums {
		declEnum(e, scope, prefix)
	}
	for _, m := range f.Messages {
		declMsg(m, scope, prefix)
	}
}

var scalarKinds = map[string]bool{
	"double": true, "float": true, "int32": true, "int64": true, "uint32": true, "uint64": true,
	"sint32": true, "sint64": true, "fixed32": true, "fixed64": true, "sfixed32": true, "sfixed64": true,
	"bool": true, "string": true, "bytes": true,
}

func resolve(m *Message) {
	f := m.File
	for _, fd := range m.Fields {
		fd.Rep = fd.Label == "repeated"
		if scalarKinds[fd.TypeName] {
			fd.Kind = fd.TypeName
		} else {
			name := fd.TypeName
			scope := m.FullName
			for {
				cand := name
				if strings.HasPrefix(name, ".") {
					cand = name[1:]
				} else if scope != "" {
					cand = scope + "." + name
				}
				if t, ok := messages[cand]; ok {
					fd.Kind, fd.Msg = "message", t
					break
				}
				if t, ok := enums[cand]; ok {
					fd.Kind, fd.Enum = "enum", t
					break
				}
				if scope == "" || strings.HasPrefix(name, ".") {
					die("%s: unknown type %s of field %s.%s", f.Path, fd.TypeName, m.FullName, fd.Name)
				}
				if i := strings.LastIndex(scope, "."); i >= 0 {
					scope = scope[:i]
				} else {
					scope = ""
				}
			}
		}
		numeric := fd.Kind != "string" && fd.Kind != "bytes" && fd.Kind != "message"
		presence := fd.Options["features.field_presence"]
		if presence == "" {
			presence = f.Options["features.field_presence"]
		}
		switch f.Syntax {
		case "proto2":
			fd.Pres = !fd.Rep
			fd.Packed = fd.Rep && numeric && fd.Options["packed"] == "true"
		case "proto3":
			fd.Pres = !fd.Rep && (fd.Label == "optional" || fd.Kind == "message" || fd.Oneof != 0)
			fd.Packed = fd.Rep && numeric && fd.Options["packed"] != "false"
			fd.Utf8 = fd.Kind == "string"
		default: // editions
			fd.Pres = !fd.Rep && (presence != "IMPLICIT" || fd.Kind == "message" || fd.Oneof != 0)
			enc := fd.Options["features.repeated_field_encoding"]
			if enc == "" {
				enc = f.Options["features.repeated_field_encoding"]
			}
			fd.Packed = fd.Rep && numeric && enc != "EXPANDED"
			fd.Utf8 = fd.Kind == "string" && f.Options["features.utf8_validation"] != "NONE"
		}
		if f.Options["java_string_check_utf8"] == "true" && fd.Kind == "string" {
			fd.Utf8 = true
		}
	}
}

// ---------------------------------------------------------------- overload naming

// method is one member of the Java API of a generated class.
type method struct {
	java    string   // Java name
	params  []string // Go parameter types
	tokens  []string // the translator's token of each parameter type
	ret     string   // Go result type
	body    string   // Go statements; %R is the receiver type
	builder bool     // exists on the Builder only
	name    string   // Go name (assigned)
}

func (m *method) sig() string { return strings.Join(m.params, ", ") }

func (m *method) suffix() string {
	if len(m.tokens) == 0 {
		return "_0"
	}
	return "_" + strings.Join(m.tokens, "_")
}

func lookupMethod(owners []string, java, params string) *extEntry {
	for i := range extMethods {
		e := &extMethods[i]
		if e.java != java || e.params != params {
			continue
		}
		for _, o := range owners {
			if e.owner == o {
				e.rel = e.goName
				return e
			}
		}
	}
	return nil
}

func lookupFunc(class, java, params string) *extEntry {
	base := class + "_" + java
	for i := range extFuncs {
		e := &extFuncs[i]
		if e.java == java && e.params == params && (e.goName == base || strings.HasPrefix(e.goName, base+"_")) {
			e.rel = strings.TrimPrefix(e.goName, class+"_")
			return e
		}
	}
	return nil
}

// assignNames gives every overload of a group (methods with one Java name,
// in order of preference) the Go name the translator uses for it.
func assignNames(group []*method, find func(m *method) *extEntry, where string) {
	plain := false
	taken := map[string]bool{}
	for _, m := range group {
		if e := find(m); e != nil {
			e.seen = true
			m.name = e.rel
			taken[m.name] = true
			if e.rel == m.java {
				plain = true
			}
			if e.ret != m.ret {
				problems = append(problems, fmt.Sprintf("%s.%s(%s): translator expects result %q, generated %q", where, m.java, m.sig(), e.ret, m.ret))
			}
		}
	}
	for _, m := range group {
		if m.name != "" {
			continue
		}
		if !plain && len(group) == 1 || !plain && !taken[m.java] {
			m.name = m.java
			plain = true
		} else {
			m.name = m.java + m.suffix()
		}
		if taken[m.name] {
			problems = append(problems, fmt.Sprintf("%s: name clash on %s", where, m.name))
		}
		taken[m.name] = true
	}
}

// ---------------------------------------------------------------- emission

type gen struct {
	sb strings.Builder
}

func (g *gen) p(format string, args ...any) {
	if len(args) == 0 {
		g.sb.WriteString(format)
	} else {
		fmt.Fprintf(&g.sb, format, args...)
	}
	g.sb.WriteByte('\n')
}

func javaDots(bin string) string { return strings.ReplaceAll(bin, "$", ".") }

func simpleName(bin string) string {
	return bin[strings.LastIndexAny(bin, ".$")+1:]
}

func (g *gen) enumType(goType, java string, names []string, nums []int, unrecognized bool, intValueOf bool) {
	g.p("")
	g.p("type %s struct {", goType)
	g.p("\tEnum")
	g.p("\tnum_ int32")
	g.p("}")
	g.p("")
	g.p("func (this *%s) up_Enum() *Enum {", goType)
	g.p("\tif this == nil {\n\t\treturn nil\n\t}")
	g.p("\treturn &this.Enum")
	g.p("}")
	g.p("")
	g.p("func new_%s_(name string, ordinal int32, num int32) *%s {", goType, goType)
	g.p("\tthis := &%s{num_: num}", goType)
	g.p("\tthis.self_ = this")
	g.p("\tthis.init_Enum(name, ordinal)")
	g.p("\treturn this")
	g.p("}")
	g.p("")
	if unrecognized {
		g.p("func (this *%s) getNumber() int32 { return pbEnumNumber_(this.num_, this == %s_UNRECOGNIZED) }", goType, goType)
	} else {
		g.p("func (this *%s) getNumber() int32 { return this.num_ }", goType)
	}
	g.p("")
	all := append([]string(nil), names...)
	if unrecognized {
		all = append(all, "UNRECOGNIZED")
		nums = append(append([]int(nil), nums...), -1)
	}
	g.p("var (")
	for i, n := range all {
		g.p("\t%s_%s = new_%s_(%q, %d, %d)", goType, n, goType, n, i, nums[i])
	}
	g.p(")")
	g.p("")
	g.p("var %s_values_ = []*%s{%s}", goType, goType, goType+"_"+strings.Join(all, ", "+goType+"_"))
	g.p("")
	if e := lookupFunc(goType, "values", ""); e != nil {
		e.seen = true
	}
	g.p("func %s_values() []*%s { return append([]*%s(nil), %s_values_...) }", goType, goType, goType, goType)
	g.p("")

	forNumber := &method{java: "forNumber", params: []string{"int32"}, tokens: []string{"int"}, ret: "*" + goType}
	valueOfS := &method{java: "valueOf", params: []string{"string"}, tokens: []string{"String"}, ret: "*" + goType}
	valueOfI := &method{java: "valueOf", params: []string{"int32"}, tokens: []string{"int"}, ret: "*" + goType}
	find := func(m *method) *extEntry { return lookupFunc(goType, m.java, m.sig()) }
	assignNames([]*method{forNumber}, find, goType)
	if intValueOf {
		assignNames([]*method{valueOfS, valueOfI}, find, goType)
	} else {
		assignNames([]*method{valueOfS}, find, goType)
	}

	g.p("func %s_%s(p0 int32) *%s {", goType, forNumber.name, goType)
	g.p("\tswitch p0 {")
	done := map[int]bool{}
	for i, n := range names {
		if done[nums[i]] {
			continue
		}
		done[nums[i]] = true
		g.p("\tcase %d:\n\t\treturn %s_%s", nums[i], goType, n)
	}
	g.p("\t}")
	g.p("\treturn nil")
	g.p("}")
	g.p("")
	g.p("func %s_%s(p0 string) *%s {", goType, valueOfS.name, goType)
	g.p("\tfor _, e := range %s_values_ {", goType)
	g.p("\t\tif e.name() == p0 {\n\t\t\treturn e\n\t\t}")
	g.p("\t}")
	g.p("\tpbEnumValueOf_(%q, p0)", javaDots(java))
	g.p("\treturn nil")
	g.p("}")
	if intValueOf {
		g.p("")
		g.p("func %s_%s(p0 int32) *%s { return %s_%s(p0) }", goType, valueOfI.name, goType, goType, forNumber.name)
	}
	g.p("")
	g.p("// %s_ofNum_ is the constant a field holding number n reads as.", goType)
	g.p("func %s_ofNum_(n int32) *%s {", goType, goType)
	g.p("\tif e := %s_%s(n); e != nil {\n\t\treturn e\n\t}", goType, forNumber.name)
	if unrecognized {
		g.p("\treturn %s_UNRECOGNIZED", goType)
	} else {
		g.p("\treturn %s_%s", goType, names[0])
	}
	g.p("}")
}

func (g *gen) enum(e *Enum) {
	var names []string
	var nums []int
	for _, v := range e.Values {
		names = append(names, v.Name)
		nums = append(nums, v.Number)
	}
	g.p("")
	g.p("// ---- enum %s", e.FullName)
	g.enumType(e.Go, e.Java, names, nums, !e.Closed, true)
	g.p("")
	g.p("const (")
	for _, v := range e.Values {
		g.p("\t%s_%s_VALUE int32 = %d", e.Go, v.Name, v.Number)
	}
	g.p(")")
	g.p("")
	var qn []string
	var sn []string
	for _, v := range e.Values {
		qn = append(qn, strconv.Quote(v.Name))
		sn = append(sn, strconv.Itoa(v.Number))
	}
	g.p("var %s_desc_ = pbRegEnum_(&pbEnumDesc_{name: %q, closed: %v,\n\tnames: []string{%s},\n\tnums: []int32{%s}})",
		e.Go, e.FullName, e.Closed, strings.Join(qn, ", "), strings.Join(sn, ", "))
}

var kindConst = map[string]string{
	"double": "pbDouble_", "float": "pbFloat_", "int64": "pbInt64_", "uint64": "pbUint64_", "int32": "pbInt32_",
	"fixed64": "pbFixed64_", "fixed32": "pbFixed32_", "bool": "pbBool_", "string": "pbString_", "message": "pbMessage_",
	"bytes": "pbBytes_", "uint32": "pbUint32_", "enum": "pbEnum_", "sfixed32": "pbSfixed32_", "sfixed64": "pbSfixed64_",
	"sint32": "pbSint32_", "sint64": "pbSint64_",
}

// scalar describes how a non-message kind appears in the Java API.
type scalar struct {
	goType string // Go type of the Java type
	token  string // translator token of the Java type
	getter string // pbData_ accessor
}

func scalarOf(fd *Field) scalar {
	switch fd.Kind {
	case "double":
		return scalar{"float64", "double", "gF64_"}
	case "float":
		return scalar{"float32", "float", "gF32_"}
	case "int64", "uint64", "sint64", "fixed64", "sfixed64":
		return scalar{"int64", "long", "gI64_"}
	case "int32", "uint32", "sint32", "fixed32", "sfixed32":
		return scalar{"int32", "int", "gI32_"}
	case "bool":
		return scalar{"bool", "boolean", "gBool_"}
	case "string":
		return scalar{"string", "String", "gStr_"}
	case "bytes":
		return scalar{"*ByteString", "ByteString", "gBytes_"}
	case "enum":
		return scalar{"*" + fd.Enum.Go, simpleName(fd.Enum.Java), ""}
	}
	panic("not a scalar: " + fd.Kind)
}

func defaultLiteral(m *Message, fd *Field) string {
	d, ok := fd.Options["default"]
	if !ok {
		return ""
	}
	switch fd.Kind {
	case "string":
		return strconv.Quote(d[1:])
	case "bytes":
		die("%s.%s: default values of bytes fields are not supported", m.FullName, fd.Name)
	case "bool":
		return d
	case "enum":
		for _, v := range fd.Enum.Values {
			if v.Name == d {
				return fmt.Sprintf("int32(%d)", v.Number)
			}
		}
		die("%s.%s: unknown default %s", m.FullName, fd.Name, d)
	case "double", "float":
		t := "float64"
		if fd.Kind == "float" {
			t = "float32"
		}
		switch d {
		case "inf":
			return t + "(posinf_)"
		case "-inf":
			return t + "(neginf_)"
		case "nan":
			return t + "(nan_)"
		}
		return t + "(" + d + ")"
	case "uint32", "fixed32":
		n, _ := strconv.ParseUint(d, 0, 32)
		return fmt.Sprintf("int32(%d)", int32(uint32(n)))
	case "uint64", "fixed64":
		n, _ := strconv.ParseUint(d, 0, 64)
		return fmt.Sprintf("int64(%d)", int64(n))
	case "int32", "sint32", "sfixed32":
		return "int32(" + d + ")"
	}
	return "int64(" + d + ")"
}

func (g *gen) message(m *Message) {
	G, GB, GO := m.Go, m.GoB, m.GoOB
	base, baseB := "GeneratedMessage", "GeneratedMessage_Builder"
	if m.Extendable {
		base, baseB = "GeneratedMessage_ExtendableMessage", "GeneratedMessage_ExtendableBuilder"
	}
	g.p("")
	g.p("// ---- message %s", m.FullName)
	g.p("")
	g.p("type %s struct {\n\t%s\n}", G, base)
	g.p("")
	g.p("func (this *%s) up_%s() *%s {\n\tif this == nil {\n\t\treturn nil\n\t}\n\treturn &this.%s\n}", G, base, base, base)
	g.p("")
	g.p("type %s struct {\n\t%s\n}", GB, baseB)
	g.p("")
	g.p("func (this *%s) up_%s() *%s {\n\tif this == nil {\n\t\treturn nil\n\t}\n\treturn &this.%s\n}", GB, baseB, baseB, baseB)

	// The descriptor.
	g.p("")
	var oneofs []string
	for _, o := range m.Oneofs {
		oneofs = append(oneofs, strconv.Quote(o))
	}
	g.p("var %s_desc_ = pbReg_(&pbDesc_{name: %q, oneofs: []string{%s},", G, m.FullName, strings.Join(oneofs, ", "))
	g.p("\tnewM: func() any { return &%s{} }, newB: func() any { return &%s{} },", G, GB)
	g.p("\tfields: []*pbField_{")
	for _, fd := range m.Fields {
		s := fmt.Sprintf("{name: %q, num: %d, kind: %s", fd.Name, fd.Number, kindConst[fd.Kind])
		if fd.Rep {
			s += ", rep: true"
		}
		if fd.Packed {
			s += ", packed: true"
		}
		if fd.Pres {
			s += ", pres: true"
		}
		if fd.Utf8 {
			s += ", utf8: true"
		}
		if fd.Oneof != 0 {
			s += fmt.Sprintf(", oneof: %d", fd.Oneof)
		}
		if d := defaultLiteral(m, fd); d != "" {
			s += ", def: " + d
		}
		if fd.Msg != nil {
			s += fmt.Sprintf(", tname: %q", fd.Msg.FullName)
		}
		if fd.Enum != nil {
			s += fmt.Sprintf(", tname: %q", fd.Enum.FullName)
		}
		g.p("\t\t%s},", s)
	}
	g.p("\t}})")
	g.p("")
	g.p("const (")
	for _, fd := range m.Fields {
		g.p("\t%s_%s_FIELD_NUMBER int32 = %d", G, strings.ToUpper(fd.Name), fd.Number)
	}
	if len(m.Fields) == 0 {
		g.p("\t%s_no_fields_ = 0", G)
	}
	g.p(")")

	// Oneof case enums.
	pkg := javaPackage(m.File)
	caseType := map[int]string{}
	for i, o := range m.Oneofs {
		java := m.Java + "$" + camel(o, true) + "Case"
		ct := goName(java, pkg)
		caseType[i+1] = ct
		var names []string
		var nums []int
		for _, fd := range m.Fields {
			if fd.Oneof == i+1 {
				names = append(names, strings.ToUpper(fd.Name))
				nums = append(nums, fd.Number)
			}
		}
		names = append(names, strings.ToUpper(o)+"_NOT_SET")
		nums = append(nums, 0)
		g.enumType(ct, java, names, nums, false, true)
	}

	// Static members.
	var statics []*method
	st := func(java string, params, tokens []string, ret, body string) {
		statics = append(statics, &method{java: java, params: params, tokens: tokens, ret: ret, body: body})
	}
	simple := simpleName(m.Java)
	st("getDefaultInstance", nil, nil, "*"+G, "return "+G+"_desc_.default_().(*"+G+")")
	st("getDescriptor", nil, nil, "*Descriptors_Descriptor", "return "+G+"_desc_.descriptor_()")
	st("newBuilder", nil, nil, "*"+GB, "return "+G+"_desc_.newBuilder_().me_.(*"+GB+")")
	st("newBuilder", []string{"*" + G}, []string{simple}, "*"+GB, "return pbBuilderFrom_("+G+"_desc_, obj_(p0)).(*"+GB+")")
	reg := "*ExtensionRegistryLite"
	for _, v := range []struct {
		param, token, expr string
	}{
		{"[]int8", "byteArr", "pbParse_(" + G + "_desc_, pbU8_(p0), false)"},
		{"*ByteString", "ByteString", "pbParse_(" + G + "_desc_, p0.b_, true)"},
		{"*CodedInputStream", "CodedInputStream", "pbParseCoded_(" + G + "_desc_, p0)"},
	} {
		st("parseFrom", []string{v.param}, []string{v.token}, "*"+G, "return "+v.expr+".(*"+G+")")
		st("parseFrom", []string{v.param, reg}, []string{v.token, "ExtensionRegistryLite"}, "*"+G, "return "+v.expr+".(*"+G+")")
	}
	g.emitGroups(statics, func(mt *method) *extEntry { return lookupFunc(G, mt.java, mt.sig()) }, G, func(mt *method) {
		g.p("")
		g.p("func %s_%s(%s) %s {\n\t%s\n}", G, mt.name, named(mt.params), mt.ret, mt.body)
	})

	// Instance members.
	var ms []*method
	both := func(java string, params, tokens []string, ret, body string) {
		ms = append(ms, &method{java: java, params: params, tokens: tokens, ret: ret, body: body})
	}
	bld := func(java string, params, tokens []string, body string) {
		ms = append(ms, &method{java: java, params: params, tokens: tokens, ret: "*" + GB, body: body + "\n\treturn this", builder: true})
	}
	bldGet := func(java string, params, tokens []string, ret, body string) {
		ms = append(ms, &method{java: java, params: params, tokens: tokens, ret: ret, body: body, builder: true})
	}
	idx := []string{"int32"}
	idxTok := []string{"int"}
	for i, fd := range m.Fields {
		N := camel(fd.Name, true)
		switch {
		case fd.Kind == "message":
			T, TB, TO := fd.Msg.Go, fd.Msg.GoB, fd.Msg.GoOB
			tok := simpleName(fd.Msg.Java)
			if !fd.Rep {
				both("has"+N, nil, nil, "bool", fmt.Sprintf("return this.has_(%d)", i))
				both("get"+N, nil, nil, "*"+T, fmt.Sprintf("return this.gMsg_(%d).(*%s)", i, T))
				both("get"+N+"OrBuilder", nil, nil, TO, fmt.Sprintf("return this.gMsg_(%d).(*%s)", i, T))
				bld("set"+N, []string{"*" + T}, []string{tok}, fmt.Sprintf("this.set_(%d, obj_(p0))", i))
				bld("set"+N, []string{"*" + TB}, []string{"Builder"}, fmt.Sprintf("this.set_(%d, p0.build())", i))
				bld("merge"+N, []string{"*" + T}, []string{tok}, fmt.Sprintf("this.mergeMsg_(%d, obj_(p0))", i))
				bld("clear"+N, nil, nil, fmt.Sprintf("this.clr_(%d)", i))
				bldGet("get"+N+"Builder", nil, nil, "*"+TB, fmt.Sprintf("return this.bld_(%d).(*%s)", i, TB))
				continue
			}
			both("get"+N+"List", nil, nil, "List", fmt.Sprintf("return this.list_(%d)", i))
			both("get"+N+"Count", nil, nil, "int32", fmt.Sprintf("return this.cnt_(%d)", i))
			both("get"+N, idx, idxTok, "*"+T, fmt.Sprintf("return this.at_(%d, p0).(*%s)", i, T))
			both("get"+N+"OrBuilder", idx, idxTok, TO, fmt.Sprintf("return this.at_(%d, p0).(*%s)", i, T))
			both("get"+N+"OrBuilderList", nil, nil, "List", fmt.Sprintf("return this.list_(%d)", i))
			bld("set"+N, []string{"int32", "*" + T}, []string{"int", tok}, fmt.Sprintf("this.setAt_(%d, p0, obj_(p1))", i))
			bld("set"+N, []string{"int32", "*" + TB}, []string{"int", "Builder"}, fmt.Sprintf("this.setAt_(%d, p0, p1.build())", i))
			bld("add"+N, []string{"*" + T}, []string{tok}, fmt.Sprintf("this.add_(%d, obj_(p0))", i))
			bld("add"+N, []string{"int32", "*" + T}, []string{"int", tok}, fmt.Sprintf("this.addAt_(%d, p0, obj_(p1))", i))
			bld("add"+N, []string{"*" + TB}, []string{"Builder"}, fmt.Sprintf("this.add_(%d, p0.build())", i))
			bld("add"+N, []string{"int32", "*" + TB}, []string{"int", "Builder"}, fmt.Sprintf("this.addAt_(%d, p0, p1.build())", i))
			bld("addAll"+N, []string{"Iterable"}, []string{"Iterable"}, fmt.Sprintf("this.addAll_(%d, p0, nil)", i))
			bld("clear"+N, nil, nil, fmt.Sprintf("this.clr_(%d)", i))
			bld("remove"+N, idx, idxTok, fmt.Sprintf("this.rm_(%d, p0)", i))
			bldGet("get"+N+"Builder", idx, idxTok, "*"+TB, fmt.Sprintf("return this.bldAt_(%d, p0).(*%s)", i, TB))
			bldGet("add"+N+"Builder", nil, nil, "*"+TB, fmt.Sprintf("return this.addBld_(%d).(*%s)", i, TB))
			bldGet("add"+N+"Builder", idx, idxTok, "*"+TB, fmt.Sprintf("return this.addBldAt_(%d, p0).(*%s)", i, TB))
			bldGet("get"+N+"BuilderList", nil, nil, "List", fmt.Sprintf("return this.bldList_(%d)", i))
		default:
			sc := scalarOf(fd)
			t, tok := []string{sc.goType}, []string{sc.token}
			isEnum := fd.Kind == "enum"
			open := isEnum && !fd.Enum.Closed
			// in: Java value p -> slot value; out: slot value -> Java value.
			in := func(p string) string {
				switch fd.Kind {
				case "enum":
					return p + ".getNumber()"
				case "bytes":
					return "obj_(" + p + ")"
				}
				return p
			}
			if !fd.Rep {
				if fd.Pres {
					both("has"+N, nil, nil, "bool", fmt.Sprintf("return this.has_(%d)", i))
				}
				if isEnum {
					both("get"+N, nil, nil, sc.goType, fmt.Sprintf("return %s_ofNum_(this.gI32_(%d))", fd.Enum.Go, i))
				} else {
					both("get"+N, nil, nil, sc.goType, fmt.Sprintf("return this.%s(%d)", sc.getter, i))
				}
				bld("set"+N, t, tok, fmt.Sprintf("this.set_(%d, %s)", i, in("p0")))
				bld("clear"+N, nil, nil, fmt.Sprintf("this.clr_(%d)", i))
				if fd.Kind == "string" {
					both("get"+N+"Bytes", nil, nil, "*ByteString", fmt.Sprintf("return this.gStrBytes_(%d)", i))
					bld("set"+N+"Bytes", []string{"*ByteString"}, []string{"ByteString"}, fmt.Sprintf("this.set_(%d, p0.toStringUtf8())", i))
				}
				if open {
					both("get"+N+"Value", nil, nil, "int32", fmt.Sprintf("return this.gI32_(%d)", i))
					bld("set"+N+"Value", idx, idxTok, fmt.Sprintf("this.set_(%d, p0)", i))
				}
				continue
			}
			conv := "nil"
			if isEnum {
				both("get"+N+"List", nil, nil, "List", fmt.Sprintf("return this.enumList_(%d, func(n int32) any { return %s_ofNum_(n) })", i, fd.Enum.Go))
				both("get"+N, idx, idxTok, sc.goType, fmt.Sprintf("return %s_ofNum_(this.at_(%d, p0).(int32))", fd.Enum.Go, i))
				conv = fmt.Sprintf("func(v any) any { return v.(*%s).getNumber() }", fd.Enum.Go)
			} else {
				both("get"+N+"List", nil, nil, "List", fmt.Sprintf("return this.list_(%d)", i))
				both("get"+N, idx, idxTok, sc.goType, fmt.Sprintf("return this.at_(%d, p0).(%s)", i, sc.goType))
			}
			both("get"+N+"Count", nil, nil, "int32", fmt.Sprintf("return this.cnt_(%d)", i))
			bld("set"+N, []string{"int32", sc.goType}, []string{"int", sc.token}, fmt.Sprintf("this.setAt_(%d, p0, %s)", i, in("p1")))
			bld("add"+N, t, tok, fmt.Sprintf("this.add_(%d, %s)", i, in("p0")))
			bld("addAll"+N, []string{"Iterable"}, []string{"Iterable"}, fmt.Sprintf("this.addAll_(%d, p0, %s)", i, conv))
			bld("clear"+N, nil, nil, fmt.Sprintf("this.clr_(%d)", i))
			if fd.Kind == "string" {
				both("get"+N+"Bytes", idx, idxTok, "*ByteString", fmt.Sprintf("return ByteString_copyFromUtf8(this.at_(%d, p0).(string))", i))
				bld("add"+N+"Bytes", []string{"*ByteString"}, []string{"ByteString"}, fmt.Sprintf("this.add_(%d, p0.toStringUtf8())", i))
			}
			if open {
				both("get"+N+"ValueList", nil, nil, "List", fmt.Sprintf("return this.list_(%d)", i))
				both("get"+N+"Value", idx, idxTok, "int32", fmt.Sprintf("return this.at_(%d, p0).(int32)", i))
				bld("set"+N+"Value", []string{"int32", "int32"}, []string{"int", "int"}, fmt.Sprintf("this.setAt_(%d, p0, p1)", i))
				bld("add"+N+"Value", idx, idxTok, fmt.Sprintf("this.add_(%d, p0)", i))
				bld("addAll"+N+"Value", []string{"Iterable"}, []string{"Iterable"}, fmt.Sprintf("this.addAll_(%d, p0, nil)", i))
			}
		}
	}
	for i, o := range m.Oneofs {
		N := camel(o, true)
		ct := caseType[i+1]
		both("get"+N+"Case", nil, nil, "*"+ct, fmt.Sprintf("return %s_ofNum_(this.case_(%d))", ct, i+1))
		bld("clear"+N, nil, nil, fmt.Sprintf("this.clrOneof_(%d)", i+1))
	}
	// Builder.mergeFrom(Foo): an overload of the inherited mergeFrom methods.
	ms = append(ms, &method{java: "mergeFrom", params: []string{"*" + G}, tokens: []string{simple}, ret: "*" + GB,
		body: "this.mergeData_(pbDataOf_(obj_(p0)))\n\treturn this", builder: true, name: "mergeFrom_" + simple})

	var iface []*method
	g.emitGroups(ms, func(mt *method) *extEntry {
		owners := []string{GB}
		if !mt.builder {
			owners = []string{GO, G, GB}
		}
		return lookupMethod(owners, mt.java, mt.sig())
	}, G, func(mt *method) {
		if !mt.builder {
			iface = append(iface, mt)
			g.p("")
			g.p("func (this *%s) %s(%s) %s {\n\t%s\n}", G, mt.name, named(mt.params), mt.ret, mt.body)
		}
		g.p("")
		g.p("func (this *%s) %s(%s) %s {\n\t%s\n}", GB, mt.name, named(mt.params), mt.ret, mt.body)
	})

	if !stubIface[GO] {
		g.p("")
		g.p("type %s interface {", GO)
		g.p("\tMessageOrBuilder")
		for _, mt := range iface {
			g.p("\t%s(%s) %s", mt.name, mt.sig(), mt.ret)
		}
		g.p("}")
	}
}

// emitGroups names the overloads of each Java name and emits every method.
func (g *gen) emitGroups(ms []*method, find func(*method) *extEntry, where string, emit func(*method)) {
	groups := map[string][]*method{}
	var order []string
	for _, mt := range ms {
		if _, ok := groups[mt.java]; !ok {
			order = append(order, mt.java)
		}
		groups[mt.java] = append(groups[mt.java], mt)
	}
	for _, java := range order {
		group := groups[java]
		var open []*method
		for _, mt := range group {
			if mt.name == "" {
				open = append(open, mt)
			}
		}
		assignNames(open, find, where)
	}
	seen := map[string]bool{}
	for _, mt := range ms {
		key := mt.name
		if seen[key] {
			problems = append(problems, fmt.Sprintf("%s: duplicate member %s (Java %s)", where, mt.name, mt.java))
			continue
		}
		seen[key] = true
		emit(mt)
	}
}

func named(params []string) string {
	var parts []string
	for i, p := range params {
		parts = append(parts, fmt.Sprintf("p%d %s", i, p))
	}
	return strings.Join(parts, ", ")
}
