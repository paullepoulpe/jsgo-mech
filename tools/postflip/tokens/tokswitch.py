import re,glob,sys
# 1. token constants (ordinal + 1, the byte a Node stores) from the enum initializer
src=open('g_Token_rhino.go').read()
toks=re.findall(r'Token_rhino_(\w+) = new_Token_rhino\("(\w+)", (\d+)\)', src)
assert toks
consts="// Code generated by the post-flip token-switch step. DO NOT EDIT.\n\npackage closure\n\n// The byte a Node stores for each Token (ordinal + 1), for switches on it.\nconst (\n"+"".join(f"\ttokOrd1_{n} uint8 = {int(o)+1}\n" for n,_,o in toks)+")\n"
names={n for n,_,_ in toks}
# 2. switch x.getToken() { case Token_rhino_A, ...: } -> switch x.ns_().token { case tokOrd1_A, ...: }
head=re.compile(r'switch (\w+(?:\.\w+\(\))*?)\.getToken\(\) \{')
total=0
for f in glob.glob('g_*.go'):
    s=open(f).read(); out=[]; i=0; n=0
    for m in head.finditer(s):
        if m.start()<i: continue
        # body: from the brace to its match
        j=m.end(); depth=1
        while depth:
            c=s[j]; depth+= (c=='{')-(c=='}'); j+=1
        body=s[m.end():j-1]
        cases=re.findall(r'(?m)^\s*case ([^:\n]*):', body)
        # only case clauses at this switch's own depth matter; require every case at any depth that
        # mentions a token to be plain token names, and skip switches with nested switches
        if 'switch ' in body: continue
        ok=all(all(re.fullmatch(r'Token_rhino_(\w+)', c.strip()) and re.fullmatch(r'Token_rhino_(\w+)', c.strip()).group(1) in names for c in cl.split(',')) for cl in cases)
        if not cases or not ok: continue
        newbody=re.sub(r'(?m)^(\s*case )([^:\n]*):', lambda mm: mm.group(1)+', '.join('tokOrd1_'+c.strip()[len('Token_rhino_'):] for c in mm.group(2).split(','))+':', body)
        out.append(s[i:m.start()]); out.append(f'switch {m.group(1)}.ns_().token {{'+newbody+'}')
        i=j; n+=1
    if n:
        out.append(s[i:]); open(f,'w').write(''.join(out)); total+=n
open('g_ztokens.go','w').write(consts)
print("token constants:",len(toks),"switches rewritten:",total)

# 3. Token_rhino_byOrd1_[x.ns_().token] == Token_rhino_A  ->  x.ns_().token == tokOrd1_A (and !=),
#    and x.getToken() == Token_rhino_A  ->  x.ns_().token == tokOrd1_A
cmp1=re.compile(r'Token_rhino_byOrd1_\[(\w+)\.ns_\(\)\.token\] (==|!=) Token_rhino_(\w+)\b')
cmp2=re.compile(r'\b(\w+)\.getToken\(\) (==|!=) Token_rhino_(\w+)\b')
n2=0
for f in glob.glob('g_*.go'):
    s=open(f).read()
    t,a=cmp1.subn(lambda m: f'{m.group(1)}.ns_().token {m.group(2)} tokOrd1_{m.group(3)}' if m.group(3) in names else m.group(0), s)
    t,b=cmp2.subn(lambda m: f'{m.group(1)}.ns_().token {m.group(2)} tokOrd1_{m.group(3)}' if m.group(3) in names else m.group(0), t)
    if t!=s: open(f,'w').write(t); n2+=a+b
print("token comparisons rewritten:",n2)
