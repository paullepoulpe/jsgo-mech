#!/usr/bin/env bash
# replay8.sh: the eighth flip's replay driver (replay7.sh with the eighth flip's base, overlay worktree flip8 and replay worktree replay8): runs replay-all.sh; when a patch fails, tries a 3-way merge of it; a clean merge becomes
# the regenerated patch of the same name in the overlay (logged in runs/replay8-adapted.txt) and the replay resumes. A manual patch that
# does not merge cleanly, or a step that fails its type check, stops the replay: no step is dropped unless steps.txt says so with a reason.
. /mnt/data/ubuntu/jm/env.sh
# replay8.sh [NAME]: the replay worktree is $B/wt/NAME (default replay8), its logs $B/logs/NAME*.log.
# REFLIP_OVERLAY=DIR: the worktree holding the overlay (steps.txt, toolfix.sh, patches) instead of $B/wt/flip8.
N=${1:-replay8}
R=${REFLIP_OVERLAY:-$B/wt/flip8}; W=$B/wt/$N; O=$R/tools/postflip/reflip/patches; cd $R
for i in $(seq 1 200); do
  tools/postflip/replay-all.sh -base f8d67cef -noverify -steps tools/postflip/reflip/steps.txt -overlay $O -toolfix tools/postflip/reflip/toolfix.sh -check "$B/bin/tc go/closure" -w $W > $B/logs/$N.log 2>&1 && { echo "REPLAY DONE"; exit 0; }
  line=$(grep "^FAILED at .*: patch " $B/logs/$N.log | tail -1)
  if [ -z "$line" ]; then
    echo "STOPPED (not a patch failure):"; tail -12 $B/logs/$N.log | cut -c1-240; exit 1
  fi
  c=$(echo "$line" | sed -E 's/^FAILED at ([0-9a-f]+):.*/\1/'); p=$(echo "$line" | sed -E 's/.*: patch //'); n=$(basename $p)
  cd $W; git reset -q --hard; git clean -q -fd go
  if git apply --3way "$p" > $B/logs/$N-3way.log 2>&1 && ! git diff --name-only --diff-filter=U | grep -q .; then
    git diff HEAD -- go > $O/$n; git reset -q --hard; git clean -q -fd go
    echo "$c $n regenerated by 3-way merge" >> $B/runs/$N-adapted.txt
    cd $R
  elif [[ $n == *-manual.patch ]]; then
    # a manual patch of generated text that this flip writes differently: the replay STOPS. The step is then decided by hand and
    # recorded in steps.txt: dropped with its reason (superseded by the translator or a prep step, with the evidence; or not
    # applicable), or redone against this flip's text as an adapted step. Nothing is dropped silently.
    echo "STOPPED: manual patch $n ($c) does not apply to this flip's text (3-way merge conflicts in: $(git diff --name-only --diff-filter=U | tr '\n' ' '))"
    git reset -q --hard; git clean -q -fd go; exit 1
  else
    echo "CONFLICT at $c $n:"; git status --short | grep -v "^M \|^A \|^D " | head -20; git reset -q --hard; git clean -q -fd go; exit 1
  fi
done
