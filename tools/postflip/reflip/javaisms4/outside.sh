#!/bin/bash
# counts of Java-isms that no census row matches (cd go/closure first)
c() { printf "%7d  %s\n" "$(cat g_*.go | grep -cE "$2")" "$1 [lines matching /$2/]"; }
o() { printf "%7d  %s\n" "$(cat g_*.go | grep -oE "$2" | wc -l)" "$1 [/$2/]"; }
o "virtual dispatch: calls of this.self_.m_impl(...) (dispatcher bodies)" 'this\.self_\.\w+_impl\('
o "virtual dispatch: exact-class tests p == this" 'p, _ := this\.self_\.\(\*\w+(\[[^]]*\])?\); p == this'
c "methods named *_impl (virtual method bodies)" '^func \([^)]*\) \w+_impl\('
o ".self() calls (most derived object of a typed value)" '\.self\(\)'
o "explicit upcasts .up_X()" '\.up_\w+\(\)'
c "X_as interfaces (class with subclasses, for casts)" '^type \w+_as interface'
c "X_I interfaces (virtual methods of a class hierarchy)" '^type \w+_I interface'
c "equals methods declared (equals, equals_X, equals_impl...)" '^func \([^)]*\) equals\w*\('
c "hashCode methods declared" '^func \([^)]*\) hashCode\w*\('
o "identity equals eqR_ / typed equals helpers equalsR_/equalsRR_/equalsBy_/objequalsBy_/equalsVia_/equalsDyn_" '\b(eqR_|equalsR_|equalsRR_|equalsBy_|objequalsBy_|equalsVia_|equalsDyn_|hashR_|hashBy_)\('
o "toString protocol: tostr*_ / objstr_ / jtostr_ helpers" '\b(tostr\w*_|objstr_|jtostr_|sstr_)\('
c "toString methods declared" '^func \([^)]*\) toString\w*\('
o "generic boxing boxT_ / unboxT_ / junboxT_" '\b(boxT_|unboxT_|junboxT_|boxValue_)\b'
o "null String sentinel nullstr_" '\bnullstr_\b'
o "Optional<String> as optstr: optstrOf_/optstrGet_/..." '\boptstr\w*_\('
o "typed-collection element descriptors used (tc_X arguments)" '\btc_\w+\b'
c "typed-collection element descriptors declared (var tc_X = &tconv_)" '^var tc_\w+ = &tconv_'
o "erased views of typed collections (.asList()/.asMap()/.asSet()/.asImm()/.asCollection())" '\.as(List|Map|Set|Imm|Collection|Iterable|Sorted)\(\)'
o "interface-upcast helpers X_as_Y( (nil-keeping conversion to a Java interface)" '\b[A-Z]\w+_as_[A-Z]\w+\('
o "erased collection interface types in declarations: ListOf[/MapOf[/SetOf[/CollectionOf[/IterableOf[/IteratorOf[/DequeOf[" '\b(List|Map|Set|Collection|Iterable|Iterator|Deque|Queue|Map_Entry)Of\['
o "erased Guava immutable types in declarations: ImmutableXOf[" '\bImmutable\w+Of\['
o "typed collections in declarations: *TList[/*TMap[/*TSet[" '\*T(List|Map|Set)\['
o "native slices in declarations []T (excluding []any, []byte)" '\[\]\*?[A-Z]\w+'
o "range loops" '\bfor [^{;]* := range '
o "utf16 views (strview): utf16_/utf16Kept_" '\butf16(Kept)?_\b'
o "Java exception objects made: new_XException/Error(" '\bnew_\w*(Exception|Error)\w*\('
o "Go error values: fmt.Errorf / errors.New / error results" '\bfmt\.Errorf\(|\berrors\.New\(|\) error \{|, error\) \{'
o "Enum.valueOf-style lookups X_valueOf(" '\b\w+_valueOf\('
o "strBuilder_ (runtime StringBuilder type) mentions" '\bstrBuilder_\b'
o "strings.Builder mentions" '\bstrings\.Builder\b'
o "inline null checks panic(new_NullPointerException" 'panic\(new_NullPointerException'
o "Java-named maps API on typed collections: .Put(/.Get(/.Has(/.Add(" '\.(Put|Get|Has|Add|ComputeIfAbsent|PutIfAbsent)\('
o "Java collection API on erased interfaces: .get(/.put(/.add(/.contains(/.containsKey(/.size(/.isEmpty(" '\.(get|put|add|contains|containsKey|size|isEmpty|addAll|remove|putAll|keySet|values|entrySet)\('
