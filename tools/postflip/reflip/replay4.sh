#!/usr/bin/env bash
# replay4.sh: runs the fourth flip's replay (replay2.sh with this flip's base and worktree); when a patch fails, tries a 3-way merge of it; a clean merge becomes
# the regenerated patch of the same name in the overlay (logged in runs/replay4-adapted.txt) and the replay resumes.
. /mnt/data/ubuntu/jm/env.sh
R=$B/wt/flip4; W=$B/wt/replay4; O=$R/tools/postflip/reflip/patches; cd $R
for i in $(seq 1 200); do
  tools/postflip/replay-all.sh -base dfdb5197 -noverify -steps tools/postflip/reflip/steps.txt -overlay $O -toolfix tools/postflip/reflip/toolfix.sh -check "$B/bin/tc go/closure" -w $W > $B/logs/replay4.log 2>&1 && { echo "REPLAY DONE"; exit 0; }
  line=$(grep "^FAILED at .*: patch " $B/logs/replay4.log | tail -1)
  if [ -z "$line" ]; then
    # a commit whose manual patch applied but no longer type-checks (it builds on a dropped manual patch): dropped too
    cc=$(grep "^CHECK FAILED after " $B/logs/replay4.log | tail -1 | sed -E 's/^CHECK FAILED after ([0-9a-f]+) .*/\1/')
    S=tools/postflip/reflip/steps.txt
    if [ -n "$cc" ] && grep -q "^$cc patch .*-manual.patch\$" $S; then
      err=$(grep -E "^go/closure/.*: " $B/logs/replay4.log | tail -1 | cut -c1-140)
      sed -i -E "s|^($cc patch (.*-manual\.patch))\$|#=2 $cc dropped (fourth flip): the manual patch applies but the package no longer type-checks\n#- \1|" $S
      echo "$cc manual patch DROPPED (type check: $err)" >> $B/runs/replay4-adapted.txt
      (cd $W && git reset -q --hard && git clean -q -fd go); continue
    fi
    echo "STOPPED (not a patch failure):"; tail -12 $B/logs/replay4.log | cut -c1-240; exit 1
  fi
  c=$(echo "$line" | sed -E 's/^FAILED at ([0-9a-f]+):.*/\1/'); p=$(echo "$line" | sed -E 's/.*: patch //'); n=$(basename $p)
  cd $W; git reset -q --hard; git clean -q -fd go
  if git apply --3way "$p" > $B/logs/replay4-3way.log 2>&1 && ! git diff --name-only --diff-filter=U | grep -q .; then
    git diff HEAD -- go > $O/$n; git reset -q --hard; git clean -q -fd go
    echo "$c $n regenerated by 3-way merge" >> $B/runs/replay4-adapted.txt
    cd $R
  elif [[ $n == *-manual.patch ]]; then
    git reset -q --hard; git clean -q -fd go; cd $R
    # a manual patch of generated text that this flip writes differently: dropped (to be re-made as a tool or counted)
    S=tools/postflip/reflip/steps.txt
    grep -q "^$c patch $n\$" $S || { echo "no steps line for $c $n"; exit 1; }
    sed -i "s|^$c patch $n\$|#=2 $c dropped (fourth flip): manual patch no longer applies to this flip's text\n#- $c patch $n|" $S
    echo "$c $n DROPPED (manual patch no longer applies)" >> $B/runs/replay4-adapted.txt
  else
    echo "CONFLICT at $c $n:"; git status --short | grep -v "^M \|^A \|^D " | head -20; git reset -q --hard; git clean -q -fd go; exit 1
  fi
done
