package com.google.javascript.jscomp.instrumentation.reporter;


import com.google.common.collect.ImmutableList;
import com.google.common.primitives.Longs;
import com.google.javascript.jscomp.CmdLineException;
import com.google.javascript.jscomp.CmdLineParser;
import com.google.javascript.jscomp.base.Io;
import com.google.javascript.jscomp.base.Json;
import com.google.javascript.jscomp.base.Outcome;
import com.google.javascript.jscomp.base.SimpleJsonException;
import com.google.javascript.jscomp.base.SimpleJsonValue;
import com.google.javascript.jscomp.instrumentation.reporter.proto.InstrumentationPoint;
import java.util.LinkedHashMap;
import java.util.Map;
import org.jspecify.annotations.Nullable;

/**
 * This class will read a file that contains the instrumentation mapping generated by the compiler
 * production instrumentation pass, and also a list of other files which are the reports sent by the
 * instrumented production code. It will then take these inputs and generate a single JSON which
 * provides a detailed breakdown of each instrumentation point.
 */
final class ProductionInstrumentationReporter {

  private String instrumentationMappingLocation = "";

  private String instrumentationReportsDirectory = "";

  private String finalResultOutput = "";

  public static void main(String[] args) {
    Outcome<Void> done = new ProductionInstrumentationReporter().doMain(args);
    if (done.isErr()) {
      Io.stderr().println(done.errorMessage());
    }
  }

  /** This function reads a file at the given filePath and converts the contents into a string. */
  public static Outcome<String> readFile(String filePath) {
    return Io.readTextStrict(filePath, Io.UTF_8);
  }

  /**
   * Reads all files found in folder and converts the contents of each file to a Map<String,
   * ProfilingData> data structure where it is a mapping of the unique param value to the encoded
   * values. The folder contains all the reports sent by the instrumented production code.
   */
  private Outcome<ImmutableList<Map<String, Long>>> getAllExecutionResults(String folder) {
    ImmutableList.Builder<Map<String, Long>> result = ImmutableList.builder();

    for (final String fileEntry : Io.listDirectory(folder)) {
      Outcome<String> executionResult = readFile(Io.pathToAbsolute(fileEntry));
      if (executionResult.isErr()) {
        return Outcome.err(executionResult.error());
      }
      Outcome<Map<String, Long>> executedInstrumentationData =
          parseJsonStringToLongMap(executionResult.get());
      if (executedInstrumentationData.isErr()) {
        return Outcome.err(executedInstrumentationData.error());
      }

      result.add(executedInstrumentationData.get());
    }

    return Outcome.ok(result.build());
  }

  /**
   * Parses a JSON document that must be an object whose values are integers or null, or the same
   * as an array of [name, value] pairs, in which a repeated name is an error.
   */
  private static Outcome<Map<String, Long>> parseJsonStringToLongMap(String json) {
    Outcome<SimpleJsonValue> parsed = Json.parse(json);
    if (parsed.isErr()) {
      return Outcome.err(parsed.error());
    }
    SimpleJsonValue document = parsed.get();
    Map<String, Long> map = new LinkedHashMap<>();
    if (document.kind() == SimpleJsonValue.Kind.OBJECT) {
      for (Map.Entry<String, SimpleJsonValue> member : document.members().entrySet()) {
        Outcome<@Nullable Long> value = readJsonLong(member.getValue());
        if (value.isErr()) {
          return Outcome.err(value.error());
        }
        map.put(member.getKey(), value.get());
      }
      return Outcome.ok(map);
    } else if (document.kind() != SimpleJsonValue.Kind.ARRAY) {
      return Outcome.err(new SimpleJsonException("Malformed report: expected a JSON object"));
    }
    for (SimpleJsonValue pair : document.elements()) {
      if (pair.kind() != SimpleJsonValue.Kind.ARRAY || pair.elements().size() != 2) {
        return Outcome.err(new SimpleJsonException("Malformed report: expected a [name, value]"));
      }
      Outcome<String> key = pair.elements().get(0).asString();
      if (key.isErr()) {
        return Outcome.err(key.error());
      }
      Outcome<@Nullable Long> value = readJsonLong(pair.elements().get(1));
      if (value.isErr()) {
        return Outcome.err(value.error());
      }
      Long replaced = map.put(key.get(), value.get());
      if (replaced != null) {
        return Outcome.err(new SimpleJsonException("duplicate key: " + key.get()));
      }
    }
    return Outcome.ok(map);
  }

  /** Reads null, or an integer that fits a long, given as a number or as a string. */
  private static Outcome<@Nullable Long> readJsonLong(SimpleJsonValue value) {
    if (value.kind() == SimpleJsonValue.Kind.NULL) {
      return Outcome.ok(null);
    }
    Outcome<String> text = value.asString();
    // Longs.tryParse accepts an optional '-' and ASCII digits whose value fits a long.
    Long result = text.isErr() ? null : Longs.tryParse(text.get());
    if (result == null) {
      return Outcome.err(new SimpleJsonException("Malformed report: expected an integer"));
    }
    return Outcome.ok(result);
  }

  /**
   * Creates a file with the given fileName (including extension) with the contents of the file
   * being provided by fileContents.
   */
  private Outcome<Void> createFile(String fileName, String fileContents) {
    return Io.writeText(fileName, Io.UTF_8, fileContents);
  }

  private Outcome<Void> doMain(String[] args) {

    parseCmdLineArguments(args);

    Outcome<Map<String, InstrumentationPoint>> mapping =
        ReportDecoder.parseMappingFromFile(instrumentationMappingLocation);
    if (mapping.isErr()) {
      return Outcome.err(mapping.error());
    }

    String folder = instrumentationReportsDirectory;

    Outcome<ImmutableList<Map<String, Long>>> listOfExecutionResults =
        getAllExecutionResults(folder);
    if (listOfExecutionResults.isErr()) {
      return Outcome.err(listOfExecutionResults.error());
    }

    return createFile(
        finalResultOutput,
        ProfilingReport.createTabSeparatedProfilingReport(
            mapping.get(), listOfExecutionResults.get()));
  }

  private void parseCmdLineArguments(String[] args) {
    CmdLineParser parser = new CmdLineParser();
    parser
        .option("--mapping_file")
        .required(true)
        .usage("The file name of the mapping generated by the production instrumentation pass.")
        .string(() -> instrumentationMappingLocation, v -> { instrumentationMappingLocation = v; });
    parser
        .option("--reports_directory")
        .required(true)
        .usage(
            "The folder/directory which contains all the reports created by the instrumented"
                + " production code.")
        .string(() -> instrumentationReportsDirectory, v -> { instrumentationReportsDirectory = v; });
    parser
        .option("--result_output")
        .required(true)
        .usage(
            "Use this flag to provide the name of the final report that will be generated by"
                + "this reporter.")
        .string(() -> finalResultOutput, v -> { finalResultOutput = v; });
    parser.setUsageWidth(80);

    Outcome<Void> parsed = parser.parseArgument(args);
    if (parsed.isErr()) {
      CmdLineException e = (CmdLineException) parsed.error();
      Io.stderr().println(e.getMessage());
      return;
    }
  }
}
