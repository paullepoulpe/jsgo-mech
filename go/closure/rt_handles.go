package closure

// Handle classes (tools/j2go/handles.txt). An object of such a class is not a
// heap struct but a 32-bit handle: `type C uint32`, 0 is null. Its fields live
// in two records per object, kept in chunks of 65536 records that are allocated
// on demand and never moved or freed:
//
//	C_ns_  fields without Go pointers (numbers, handles, enums as ordinal+1);
//	       the chunk is allocated pointer-free, so the collector never scans it
//	C_ps_  the other fields
//
// Everything class-specific (the records, the chunk tables C_ns_chunks_ and
// C_ps_chunks_, the accessors ns_() and ps_(), C_alloc_, box_ and C_of_) is
// generated by j2go next to the class's methods. This file is the rest.
//
// Null: chunk 0 of every table stays nil, so the first handle is 65536 and
// `C(0).ns_()` indexes through a nil chunk pointer. That is an ordinary Go nil
// dereference, which catch_ turns into a NullPointerException, exactly as for
// a nil *struct; the accessor has no test for null.

import (
	"fmt"
	"os"
	"strings"
	"unsafe"
)

const (
	handleShift_     = 16
	handleChunkSize_ = 1 << handleShift_
	handleChunks_    = 1 << (32 - handleShift_)
)

// handleGrow_ is called before the chunk of handle h is allocated.
func handleGrow_(h uint32) {
	if h == 0 {
		panic(new_RuntimeException_String("handle store: more than 2^32 objects of one class").self())
	}
}

// handleHash_ is the identity hash of a handle: the mixing identityHash_ applies
// to addresses, applied to the handle's value.
func handleHash_(h uint32) int32 {
	return int32((uint64(h)*0x9E3779B97F4A7C15)>>33) & 0x7fffffff
}

type eface_ struct{ typ, data unsafe.Pointer }

// handleBox_ is the interface value holding the handle that *self holds, where
// proto is any interface value of the handle's type. It allocates nothing: the
// interface's data word points at self, a field of the handle's own
// pointer-free record that holds the handle's value and never changes.
func handleBox_(proto any, self *uint32) any {
	(*eface_)(unsafe.Pointer(&proto)).data = unsafe.Pointer(self)
	return proto
}

// handleStats_ has one function per handle class: its object and per-field counts.
var handleStats_ []func() string

func handleStatsText_(class string, count uint32, fields []string, set []int) string {
	n := int(count) - handleChunkSize_
	var sb strings.Builder
	fmt.Fprintf(&sb, "handle class %s: %d objects, %d chunks\n", class, n, (n+handleChunkSize_-1)>>handleShift_)
	for i, f := range fields {
		fmt.Fprintf(&sb, "  %-40s set in %9d (%5.1f%%)\n", f, set[i], 100*float64(set[i])/float64(max(n, 1)))
	}
	return sb.String()
}

func init() {
	if os.Getenv("JSGO_HANDLE_STATS") == "" {
		return
	}
	flush := flushStd_
	flushStd_ = func() {
		flush()
		for _, f := range handleStats_ {
			fmt.Fprint(os.Stderr, f())
		}
	}
}
